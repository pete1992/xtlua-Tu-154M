module_script_kind module::classify_script(const char * script_path)
{
	if(script_path == NULL)
		return module_script_kind::xtlua;

#if IBM
	FILE * script = _wfopen(utf8_decode(script_path).c_str(), L"rb");
#else
	FILE * script = fopen(script_path, "rb");
#endif
	if(script == NULL)
		return module_script_kind::xtlua;

	char first_line[64] = {};
	const bool read_line = fgets(first_line, sizeof(first_line), script) != NULL;
	fclose(script);
	if(!read_line)
		return module_script_kind::xtlua;

	size_t length = strlen(first_line);
	while(length > 0 &&
		(first_line[length - 1] == '\r' || first_line[length - 1] == '\n'))
	{
		first_line[--length] = 0;
	}
	if(strcmp(first_line, "--[[ XLua 2.0 ]]") == 0)
		return module_script_kind::xlua2;

	// Der lokale Kompatibilitaetsvertrag waehlt XLua 2 nur mit dem exakten
	// Marker oben. Andere XLua-Versionsmarker werden trotzdem erkannt, damit ein
	// 2.x-/zukuenftiges XLua-Skript niemals stillschweigend als xtlua_worker
	// gestartet wird.
	static const std::regex version_marker(
		R"(^--\[\[\s*XLua\s+((?:\d+\.?){1,3})\s*\]\])");
	std::cmatch match;
	if(std::regex_search(first_line, match, version_marker))
	{
		const long major = strtol(match[1].str().c_str(), NULL, 10);
		return major >= 2 ? module_script_kind::unsupported_xlua :
			module_script_kind::xtlua;
	}

	const string marker_text(first_line);
	if(marker_text.rfind("--[[", 0) == 0 &&
		marker_text.find("XLua") != string::npos)
	{
		return module_script_kind::unsupported_xlua;
	}
	return module_script_kind::xtlua;
}
