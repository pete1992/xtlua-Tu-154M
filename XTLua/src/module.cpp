// Liefert den Zeiger auf den Dateinamen innerhalb eines Pfades
// ("a/b/c.lua" -> "c.lua"). NULL-sicher.
static const char * shorten_to_file(const char * path)
{
	if(path == NULL)
		return "";

	const char * p = path, * t = path;
	while(*p)
	{
		if(*p == '/' || *p == '\\')
			t = p + 1;
		++p;
	}
	return t;
}

// Laenge des Verzeichnisanteils (inkl. abschliessendem Separator).
static ptrdiff_t length_of_dir(const char * p)
{
	if(p == NULL)
		return 0;

	const char * f = shorten_to_file(p);
	return f - p;
}

// FIX M5: In der urspruenglichen Implementierung wurde 'boiler_plate_paths' aus in_init_script berechnet
// und dann blind auf in_module_script addiert. Liegt das Modul-Skript in einem
// kuerzeren Pfad als das init-Skript, zeigt 'path + dir_len' HINTER das
// Stringende -> Lua liest fremden Speicher als Chunknamen.
// Hier wird der Offset nur benutzt, wenn er in den String passt; ansonsten
// fallen wir auf den reinen Dateinamen zurueck.
static const char * chunk_name_for(const char * path, ptrdiff_t dir_len)
{
	if(path == NULL)
		return "?";

	size_t len = strlen(path);
	if(dir_len <= 0 || (size_t) dir_len > len)
		return shorten_to_file(path);

	return path + dir_len;
}

// FIX M3: lua_tostring kann NULL liefern (Nicht-String-Fehlerobjekt), und bei
// leerem Stack ist der Zugriff auf Index -1 undefiniert. Beides wird hier
// abgefangen, damit die Fehlermeldung selbst nicht zum Crash fuehrt.
static const char * safe_lua_error(lua_State * L)
{
	if(L == NULL)
		return "(no interpreter)";
	if(lua_gettop(L) == 0)
		return "(no error message on stack)";

	const char * s = lua_tostring(L, -1);
	return s ? s : "(non-string error object)";
}

static int xlua2_dofile(lua_State * L)
{
	module * owner = module::module_from_interp(L);
	if(owner == NULL || !owner->is_xlua2())
		return luaL_error(L, "XLua 2 module context unavailable");

	const char * relative_path = luaL_checkstring(L, 1);
	lua_settop(L, 1);
	const int load_result = owner->load_module_relative_path(relative_path);
	if(load_result != 0)
		return lua_error(L);

	// Remove the path argument, execute the loaded chunk, and preserve all
	// return values just like Lua's standard dofile().
	lua_remove(L, 1);
	lua_call(L, 0, LUA_MULTRET);
	return lua_gettop(L);
}

// Keep the complete original closure: generated bindings may acquire upvalues
// in a later SDK. A raw function-pointer call would silently lose that context.
static int xlua2_binding_dispatch(lua_State * L)
{
	module * owner = module::module_from_interp(L);
	if(owner == NULL || !owner->is_xlua2() || owner->is_closing())
		return luaL_error(L, "XLua 2 bindings unavailable while module is closing");
	const int argument_count = lua_gettop(L);
	lua_pushvalue(L, lua_upvalueindex(1));
	lua_insert(L, 1);
	// Protect the depth counter from Lua longjmp; SDK enumeration callbacks
	// must work even in top-level code or XPluginStart/XPluginEnable.
	owner->enter_sdk_call();
	const int result = lua_pcall(L, argument_count, LUA_MULTRET, 0);
	owner->leave_sdk_call();
	if(result != 0)
		return lua_error(L);
	return lua_gettop(L);
}

static void guard_xlua2_bindings(lua_State * L)
{
	// Run once, before aircraft code can retain unguarded SDK function aliases.
	// Only replace existing values, never mutate the key set while traversing.
	lua_pushnil(L);
	while(lua_next(L, LUA_GLOBALSINDEX) != 0)
	{
		if(lua_type(L, -2) == LUA_TSTRING && lua_iscfunction(L, -1))
		{
			const char * name = lua_tostring(L, -2);
			if(strncmp(name, "XPLM", 4) == 0 || strncmp(name, "XLua", 4) == 0)
			{
				lua_pushvalue(L, -2);
				lua_pushvalue(L, -2);
				lua_pushcclosure(L, xlua2_binding_dispatch, 1);
				lua_rawset(L, LUA_GLOBALSINDEX);
			}
		}
		lua_pop(L, 1);
	}
}

static int module_print(lua_State * L)
{
	// Use Lua's tostring contract (including __tostring) before owning C++
	// strings, so a Lua error cannot skip their destructors through longjmp.
	const int argument_count = lua_gettop(L);
	luaL_Buffer buffer;
	luaL_buffinit(L, &buffer);
	for(int i = 1; i <= argument_count; ++i)
	{
		if(i > 1)
			luaL_addchar(&buffer, '\t');
		lua_getglobal(L, "tostring");
		lua_pushvalue(L, i);
		lua_call(L, 1, 1);
		size_t length = 0;
		const char * value = lua_tolstring(L, -1, &length);
		if(value == NULL)
			return luaL_error(L, "tostring must return a string for print");
		luaL_addvalue(&buffer); // consumes the value, including buffer flushes
	}
	luaL_pushresult(&buffer);
	size_t length = 0;
	const char * output = lua_tolstring(L, -1, &length);
	module * owner = module::module_from_interp(L);
	string log_line("XTLua: ");
	if(owner != NULL)
	{
		switch(owner->get_runtime())
		{
		case module_runtime::xtlua_worker: log_line += "xtlua_worker: "; break;
		case module_runtime::xtlua_main: log_line += "xtlua_main: "; break;
		case module_runtime::xlua2_main: log_line += "xlua2_main: "; break;
		}
		log_line += owner->get_script_path();
		log_line += ": ";
	}
	log_line.append(output, length);
	log_line += '\n';
	xtlua_queue_log(std::move(log_line));
	return 0;
}

