int module::debug_proc_from_interp(lua_State * interp)
{
	module * me = module_from_interp(interp);
	if(me)
		return me->m_debug_proc;
	return 0;
}

module * module::module_from_interp(lua_State * interp)
{
	if(interp == NULL)
		return NULL;

	lua_pushlightuserdata(interp, &s_module_registry_key);
	lua_rawget(interp, LUA_REGISTRYINDEX);

	if(lua_islightuserdata(interp, -1))
	{
		module * me = (module *) lua_touserdata(interp, -1);
		lua_pop(interp, 1);
		return me;
	}
	else
	{
		lua_pop(interp, 1);
		return NULL;
	}
}

void * module::module_alloc_tracked(size_t amount)
{
	// Rueckgabe kann jetzt NULL sein (OOM oder absurde Groesse) - Aufrufer
	// sollten das pruefen. Vorher war ein NULL hier ein sicherer Crash im
	// Allocator selbst.
	return alloc_from_block(m_memory, amount);
}

