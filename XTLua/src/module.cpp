// 3. BUMP-ALLOCATOR
//------------------------------------------------------------------------------
// Sehr einfacher "Arena"-Allocator: Bloecke werden verkettet, innerhalb eines
// Blocks wird nur ein Zeiger hochgeschoben. Einzelfreigaben gibt es nicht -
// alles stirbt gemeinsam im Destruktor (destroy_alloc_block).
//==============================================================================

#define MALLOC_CHUNK_SIZE 4096   // Nutzlast pro Standardblock (NICHT Gesamtgroesse!)

struct module_alloc_block {
	module_alloc_block *	next;
	char *					ptr;		// naechste freie Adresse in data[]
	size_t					remaining;	// noch freie Bytes ab ptr
	char					data[MALLOC_CHUNK_SIZE];
};

// Alignment fuer alle Rueckgaben. data[] folgt auf drei zeigergrosse Felder,
// ist also mindestens sizeof(void*)-aligned; mehr koennen wir ohne
// alignas/Padding nicht garantieren. Fuer double/int64 ist das auf allen von
// X-Plane unterstuetzten Plattformen ausreichend.
static const size_t kAllocAlign = sizeof(void *);

// FIX M1: Die urspruengliche Implementierung rief malloc(MALLOC_CHUNK_SIZE) fuer eine Struktur auf,
// die MALLOC_CHUNK_SIZE + Header gross ist, und setzte remaining anschliessend
// auf die vollen MALLOC_CHUNK_SIZE. Jeder Block hat also ueber sein Ende hinaus
// geschrieben (Heap-Corruption, typischerweise als Absturz an ganz anderer
// Stelle sichtbar). Jetzt wird korrekt Header + Nutzlast reserviert.
// Ausserdem: assert(r) hilft im Release-Build nicht -> echter NULL-Pfad.
static module_alloc_block * make_alloc_block(size_t payload)
{
	if(payload < MALLOC_CHUNK_SIZE)
		payload = MALLOC_CHUNK_SIZE;

	// Overflow-Schutz fuer die Additions-Rechnung.
	const size_t hdr = offsetof(module_alloc_block, data);
	if(payload > (size_t) -1 - hdr)
		return NULL;

	module_alloc_block * r = (module_alloc_block *) malloc(hdr + payload);
	if(r == NULL)
	{
		module_log("xtlua: module allocator out of memory (%zu bytes)\n",
				   hdr + payload);
		return NULL;
	}

	r->next = NULL;
	r->ptr = r->data;
	r->remaining = payload;
	return r;
}

// FIX M2:
//   a) 'assert(amt <= MALLOC_CHUNK_SIZE)' war im Release wirkungslos -> eine
//      grosse Anfrage hat den Block ueberschrieben. Uebergrosse Anfragen
//      bekommen nun einen eigenen, passend dimensionierten Block.
//   b) Keine Alignment-Rundung: nach einer 3-Byte-Anfrage war jede folgende
//      Adresse schief (auf ARM/32-Bit real problematisch).
//   c) Ein fehlgeschlagenes make_alloc_block wurde ungeprueft dereferenziert.
//   d) amt == 0 gab zweimal dieselbe Adresse zurueck.
static void * alloc_from_block(module_alloc_block *& head, size_t amt)
{
	if(amt == 0)
		amt = 1;

	// auf kAllocAlign aufrunden, overflow-sicher
	if(amt > (size_t) -1 - (kAllocAlign - 1))
		return NULL;
	amt = (amt + (kAllocAlign - 1)) & ~(kAllocAlign - 1);

	// Schnellpfad: passt in den aktuellen Block.
	if(head != NULL && head->remaining >= amt)
	{
		void * r = head->ptr;
		head->ptr += amt;
		head->remaining -= amt;
		return r;
	}

	module_alloc_block * nb = make_alloc_block(amt);
	if(nb == NULL)
		return NULL;					// Aufrufer MUSS auf NULL pruefen

	void * r = nb->ptr;
	nb->ptr += amt;
	nb->remaining -= amt;

	if(head == NULL)
	{
		head = nb;
	}
	else if(amt > MALLOC_CHUNK_SIZE)
	{
		// Sonderblock ist bereits voll ausgereizt -> hinter head einhaengen,
		// damit der Restplatz im aktuellen head weiter nutzbar bleibt.
		nb->next = head->next;
		head->next = nb;
	}
	else
	{
		nb->next = head;
		head = nb;					// neuer Block wird aktiver Block
	}

	return r;
}

static void destroy_alloc_block(module_alloc_block * head)
{
	while(head)
	{
		module_alloc_block * k = head;
		head = head->next;
		free(k);
	}
}

