// FIX M3/M7: Kein printf mehr, kein Zugriff auf einen moeglicherweise leeren
// Lua-Stack, und lua_close wird nur bei gueltigem State aufgerufen.
// Wichtig: Das Makro fuehrt ein 'return' aus - der Aufrufer erkennt das
