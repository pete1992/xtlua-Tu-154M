int module::load_module_relative_path(const string& path)
{
	// FIX M9: luaL_error() mit NULL-State war ein sicherer Crash. Kann eintreten,
	// wenn der Konstruktor gescheitert ist und das Objekt trotzdem benutzt wird.
	if(m_interp == NULL)
		return -1;

	string script_path = m_path + path;

	xmap_class script_text(script_path);
	if(!script_text.exists())
	{
		// luaL_error() macht ein longjmp innerhalb des Lua-Aufrufs -
		// Return a status instead: the caller raises after our locals unwind.
		lua_pushfstring(m_interp, "Unable to load script file: %s", path.c_str());
		return LUA_ERRFILE;
	}

	return luaL_loadbuffer(m_interp,
						   (const char *) script_text.begin(),
						   script_text.size(),
						   path.c_str());
}

