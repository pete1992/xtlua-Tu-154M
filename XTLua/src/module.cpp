// FIX M8: Die urspruengliche Implementierung ignorierte I/O-Fehler:
//   - ftell() == -1 (z.B. Verzeichnis statt Datei) wurde als riesiges size_t
//     interpretiert -> malloc scheitert -> m_buffer == NULL, m_size aber gesetzt
//     -> exists() lieferte fuer NULL-Buffer bereits false, aber der
//        Rueckgabewert von malloc wurde ungeprueft an fread gegeben.
//   - eine unvollstaendige Leseoperation blieb unbemerkt -> Lua bekam
//     uninitialisierten Speicher als Skript.
// Jetzt: jeder Schritt geprueft, m_size == tatsaechlich gelesene Bytes.
xmap_class::xmap_class(const string& in_file_name) :
	m_buffer(NULL), m_size(0)
{
#if IBM
	FILE * fi = _wfopen(utf8_decode(in_file_name).c_str(), L"rb");
#else
	FILE * fi = fopen(in_file_name.c_str(), "rb");
#endif
	if(fi == NULL)
		return;

	if(fseek(fi, 0, SEEK_END) != 0)
	{
		fclose(fi);
		return;
	}

	long end = ftell(fi);
	if(end < 0)					// A zero-byte Lua file is a valid empty chunk.
	{
		fclose(fi);
		return;
	}

	if(fseek(fi, 0, SEEK_SET) != 0)
	{
		fclose(fi);
		return;
	}

	char * buf = (char *) malloc(end == 0 ? 1 : (size_t) end);
	if(buf == NULL)
	{
		fclose(fi);
		return;
	}

	size_t bytes = fread(buf, 1, (size_t) end, fi);
	fclose(fi);

	if(bytes != static_cast<size_t>(end))
	{
		free(buf);
		return;
	}

	m_buffer = buf;
	m_size   = bytes;				// nur der wirklich gelesene Teil
}

