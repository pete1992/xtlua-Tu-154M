void module::xplugin_receive_message(
	int inFromWho,
	int inMessage,
	void * inParam)
{
	if(m_runtime != module_runtime::xlua2_main || m_interp == NULL || !m_enabled)
		return;

	lua_getfield(m_interp, LUA_GLOBALSINDEX, "XPluginReceiveMessage");
	if(!lua_isfunction(m_interp, -1))
	{
		lua_pop(m_interp, 1);
		return;
	}

	setup_std_vars(m_interp, m_debug_proc);
	const int debug_index = lua_gettop(m_interp);
	lua_pushtraceback(m_interp);
	lua_insert(m_interp, debug_index);
	lua_pushinteger(m_interp, inFromWho);
	lua_pushinteger(m_interp, inMessage);
	const string param_type = xlua2_event_param_type(inMessage);
	if(param_type == "*u")
	{
		if(inParam != NULL)
			lua_pushinteger(m_interp, *static_cast<const int *>(inParam));
		else
			lua_pushnil(m_interp);
	}
	else if(param_type == "i" || param_type.rfind("extdata<", 0) == 0)
	{
		lua_pushinteger(
			m_interp,
			static_cast<lua_Integer>(reinterpret_cast<intptr_t>(inParam)));
	}
	else if(inParam == NULL)
	{
		lua_pushnil(m_interp);
	}
	else
	{
		// Preserve opaque third-party pointers in the same full-userdata shape
		// accepted by the generated XPLMSendMessageToPlugin binding.
		xlua_pushuserdata<void *>(m_interp, inParam);
	}

	if(lua_pcall(m_interp, 3, 0, debug_index) != 0)
	{
		module_log("xtlua: %s XPluginReceiveMessage failed: %s\n",
			m_script_path.c_str(), safe_lua_error(m_interp));
		lua_pop(m_interp, 1);
	}
	lua_remove(m_interp, debug_index);
}

